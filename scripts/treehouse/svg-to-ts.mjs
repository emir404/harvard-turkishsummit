// Turns the SVG written by treehouse.py into the path module the site imports.
// usage: node scripts/treehouse/svg-to-ts.mjs <drawing.svg> [src/components/treehouse/paths.ts]
import { readFileSync, writeFileSync } from "node:fs";

const [input, output = "src/components/treehouse/paths.ts"] = process.argv.slice(2);
if (!input) {
  console.error("usage: node scripts/treehouse/svg-to-ts.mjs <drawing.svg> [out.ts]");
  process.exit(1);
}

const svg = readFileSync(input, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
const names = { C: "detail", B: "secondary", A: "primary" };
const layers = [...svg.matchAll(/<path data-w="(\w)" stroke-width="([\d.]+)" stroke-opacity="([\d.]+)" d="([^"]+)"/g)].map(
  ([, weight, strokeWidth, opacity, d]) => ({ id: names[weight], strokeWidth: Number(strokeWidth), opacity: Number(opacity), d }),
);
if (!viewBox || layers.length !== 3) {
  console.error("Unexpected SVG: expected a viewBox and three weighted paths.");
  process.exit(1);
}

const body = `// Generated by scripts/treehouse/svg-to-ts.mjs from the treehouse.py drawing. Do not edit by hand.

export const TREEHOUSE_VIEW_BOX = ${JSON.stringify(viewBox)};

export const treehouseLayers = ${JSON.stringify(layers, null, 2)} as const;
`;
writeFileSync(output, body);
console.log(`wrote ${output} (${layers.map((l) => `${l.id}: ${l.d.length}`).join(", ")} chars)`);
