"""Isometric drawings for the summit site, in the hero's projection.

Regenerate from the repo root (needs Blender 4.2+ on the PATH; no add-ons):

    blender -b --factory-startup --python scripts/iso/render.py -- all
    blender -b --factory-startup --python scripts/iso/render.py -- bosphorus treehouse
    blender -b --factory-startup --python scripts/iso/render.py -- all --preview /some/dir

Models: dioramas.py (keynote, biotech, energy, economy, geopolitics, gala),
bosphorus.py, treehouse_iso.py, and the legacy strokes-only `bridge` in
models.py (which also holds the registry). Shared pieces are in kit.py and
geom.py.

Rendering (hlr.py): silhouettes, creases and intersection lines with hidden
lines removed by ray casting; then, for drawings with fills, regions.py maps
the regions those lines enclose, labels each by casting a ray into it (tone
from the hero's light, or a lit pane), and merges neighbours with the same
label. Output goes to src/components/iso/drawings/<name>.ts as IsoDrawingData
(paths, fills, lights, anchors); --preview also writes a JSON copy.
"""
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import hlr  # noqa: E402
import models  # noqa: E402

ROOT = HERE.parent.parent
OUT = ROOT / "src" / "components" / "iso" / "drawings"


def literal(data, indent="  "):
    """An IsoDrawingData object literal."""
    i1, i2 = indent, indent + "  "
    lines = ["{", f'{i1}viewBox: "{data["viewBox"]}",']
    if data.get("anchors"):
        inner = ", ".join(f"{k}: [{hlr.fmt(v[0])}, {hlr.fmt(v[1])}]" for k, v in data["anchors"].items())
        lines.append(f"{i1}anchors: {{ {inner} }},")
    lines.append(f"{i1}paths: [")
    for p in data["paths"]:
        lines.append(f'{i2}{{ d: "{p["d"]}", k: {p["k"]}, o: {p["o"]} }},')
    lines.append(f"{i1}],")
    if "fills" in data:
        lines.append(f"{i1}fills: [")
        for f in data["fills"]:
            lines.append(f'{i2}{{ d: "{f["d"]}", t: {f["t"]} }},')
        lines.append(f"{i1}],")
        lines.append(f"{i1}lights: [")
        for li in data["lights"]:
            lines.append(f'{i2}{{ d: "{li["d"]}", s: {li["s"]} }},')
        lines.append(f"{i1}],")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


HEADER = "// Generated by scripts/iso/render.py from the models in scripts/iso. Do not edit by hand."


def write_ts(name, data):
    text = "\n".join([HEADER, 'import type { IsoDrawingData } from "../types";', "", f"export const {name}: IsoDrawingData = {literal(data)};", ""])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.ts").write_text(text)


def run(spec):
    data = hlr.render(
        spec["parts"],
        spec["wires"],
        frame=spec["frame"],
        scale=spec["scale"],
        order=spec["order"],
        clip=spec.get("clip", False),
        chunk=spec.get("chunk"),
        fills=spec.get("fills", False),
    )
    if spec.get("anchors"):
        data["anchors"] = {k: hlr.to_view(spec["frame"], spec["scale"], p) for k, p in spec["anchors"].items()}
    return data


def write_layers(name, bundle, preview):
    """The animated Bosphorus: water, land, the moving vessels and the deck lanes, in one module."""
    from geom import vec

    print("  water")
    water = run(bundle["water"])
    w, h = water["width"], water["height"]
    tone = hlr.shade(hlr.MATERIALS["water"], vec(0, 1, 0))
    water["fills"] = [{"d": f"M0 0L{hlr.fmt(w)} 0 {hlr.fmt(w)} {hlr.fmt(h)} 0 {hlr.fmt(h)}Z", "t": tone}]
    water["lights"] = []
    print("  land")
    land = run(bundle["land"])
    ferries = []
    for f in bundle["ferries"]:
        print(f"  vessel z={f['z']}")
        ferries.append({"data": run(f["spec"]), "travel": f["travel"], "seconds": f["seconds"]})
    lanes = bundle["lanes"]
    pts = lambda pl: "[" + ", ".join(f"[{hlr.fmt(x)}, {hlr.fmt(y)}]" for x, y in pl) + "]"
    out = [
        HEADER,
        'import type { IsoDrawingData } from "../types";',
        "",
        "/** The strait itself: its face and its swell. Drawn first. */",
        f"export const bosphorusWater: IsoDrawingData = {literal(water)};",
        "",
        "/** Shores, buildings, trees and the bridge: drawn last, over the vessels, so the deck, towers, piers and quays hide them. */",
        f"export const bosphorusLand: IsoDrawingData = {literal(land)};",
        "",
        "/**",
        " * Vessels, each drawn at the start of its pass (off the picture); move one by `travel` (viewBox units)",
        " * over `seconds`, between the water and the land.",
        " */",
        "export const bosphorusFerries: { data: IsoDrawingData; travel: [number, number]; seconds: number }[] = [",
    ]
    for f in ferries:
        out.append(f"  {{\n    data: {literal(f['data'], '      ')},\n    travel: [{hlr.fmt(f['travel'][0])}, {hlr.fmt(f['travel'][1])}],\n    seconds: {f['seconds']},\n  }},")
    out += [
        "];",
        "",
        "/** The two carriageways of the deck and its approaches (traffic keeps right), for headlights and taillights. */",
        "export const bosphorusLanes: { europeToAsia: [number, number][]; asiaToEurope: [number, number][] } = {",
        f"  europeToAsia: {pts(lanes['europeToAsia'])},",
        f"  asiaToEurope: {pts(lanes['asiaToEurope'])},",
        "};",
        "",
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.ts").write_text("\n".join(out))
    if preview:
        preview.mkdir(parents=True, exist_ok=True)
        dump = {"water": water, "land": land, "ferries": ferries, "lanes": lanes,
                "routes": [{"x": f["x"], "z": f["z"]} for f in bundle["ferries"]]}
        (preview / f"{name}.json").write_text(json.dumps(dump))
    size = (OUT / f"{name}.ts").stat().st_size
    print(f"  water {len(water['paths'])} paths; land {len(land['paths'])} paths, {len(land['fills'])} fills, {len(land['lights'])} lights; "
          + "; ".join(f"vessel {len(f['data']['paths'])}/{len(f['data']['fills'])}/{len(f['data']['lights'])}" for f in ferries)
          + f"; {size / 1024:.1f} KB")


def main(argv):
    preview = None
    if "--preview" in argv:
        i = argv.index("--preview")
        preview = Path(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    names = argv or ["all"]
    if names == ["all"]:
        names = [name for name in models.DRAWINGS if name not in models.RETIRED]
    for name in names:
        t = time.time()
        print(f"{name}:")
        spec = models.DRAWINGS[name]()
        if spec.get("bundle"):
            write_layers(name, spec, preview)
            print(f"  {time.time() - t:.1f}s")
            continue
        data = run(spec)
        write_ts(name, data)
        if preview:
            preview.mkdir(parents=True, exist_ok=True)
            (preview / f"{name}.json").write_text(json.dumps(data))
        size = (OUT / f"{name}.ts").stat().st_size
        extra = f", {len(data['fills'])} fills, {len(data['lights'])} lights" if "fills" in data else ""
        print(f"  viewBox {data['viewBox']}, {len(data['paths'])} paths{extra}, {size / 1024:.1f} KB, {time.time() - t:.1f}s")


if __name__ == "__main__":
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    main(args)
